export const perSqft = (lakhs, area) => `₹${((lakhs * 100000) / area / 1000).toFixed(2)} K/sq.ft`
/** Indicative EMI: 80% loan, 8.5% p.a., 20 years */
export const emiK = (lakhs, down = 0.2, rate = 8.5, years = 20) => {
  const P = lakhs * 100000 * (1 - down)
  const r = rate / 12 / 100
  const n = years * 12
  const emi = (P * r * Math.pow(1 + r, n)) / (Math.pow(1 + r, n) - 1)
  return emi
}
